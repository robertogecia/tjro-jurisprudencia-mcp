export const chaveRelator = (nome) =>
  String(nome || "").toLowerCase().normalize("NFD").replace(/\p{M}/gu, "").replace(/[^a-z0-9]+/g, " ").trim();

/** Grafias conhecidas do relator `nome` (semente + recibos locais): {grafia: {n, anos:[de, ate]}}. */
export function grafiasConhecidas(nome, recibos = []) {
  const k = chaveRelator(nome);
  const out = {};
  if (!k) return out;
  for (const [g, v] of Object.entries(GRAFIAS_RELATOR[k] || {})) out[g] = { n: v.n, anos: [...v.anos] };
  for (const r of recibos) {
    const g = String((r && r.relator_indice) || "").trim();
    if (!g || chaveRelator(g) !== k) continue;
    const m = /(\d{4})/.exec(String((r && (r.julgado_em || r.data_julgamento || r.data)) || "").slice(-10));
    const ano = m ? m[1] : "";
    const v = out[g] || (out[g] = { n: 0, anos: ["", ""] });
    v.n += 1;
    if (ano) { if (!v.anos[0] || ano < v.anos[0]) v.anos[0] = ano; if (!v.anos[1] || ano > v.anos[1]) v.anos[1] = ano; }
  }
  return out;
}

const anosDe = (v) => (v.anos[0] && v.anos[1] ? (v.anos[0] === v.anos[1] ? v.anos[0] : `${v.anos[0]}–${v.anos[1]}`) : "anos não registrados");

/** Aviso quando relator= cobre só parte das grafias conhecidas; "" quando não há outra grafia. */
export function avisoGrafiaRelator(relator, recibos = []) {
  const pedida = String(relator || "").trim();
  if (!pedida) return "";
  const todas = grafiasConhecidas(pedida, recibos);
  const outras = Object.keys(todas).filter((g) => g !== pedida).sort();
  if (!outras.length) return "";
  const minha = todas[pedida];
  const lista = outras.map((g) => `"${g}" (${anosDe(todas[g])}, ${todas[g].n} julgado${todas[g].n > 1 ? "s" : ""} vistos)`).join(" e ");
  return (
    `⚠️ relator="${pedida}": o índice também guarda este(a) relator(a) como ${lista}. O filtro é exato e só traz a grafia pedida` +
    (minha ? ` (${anosDe(minha)}, ${minha.n} vistos)` : " (grafia ainda não vista nesta máquina)") +
    `; a outra fica FORA desta página e da linha do tempo, o que simula queda ou mudança de entendimento no ano da troca. ` +
    `Para cobrir o resto, repita com relator=${outras.map((g) => `"${g}"`).join(" ou ")} (uma requisição a mais, pelo ritmo do portal).`
  );
}
